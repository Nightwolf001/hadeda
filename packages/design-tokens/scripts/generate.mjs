// Turns tokens.json (exported from the Hadeda Design System) into src/index.ts.
// Re-run after updating tokens.json: `pnpm tokens`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));
const theme = tokens.color.themes[0].id;

const raw = Object.fromEntries(
  tokens.color.tokens.map((t) => [t.name, typeof t.value === 'string' ? t.value : t.value[theme]]),
);
const resolve = (v, depth = 0) => {
  const m = /^\{(.+)\}$/.exec(v);
  if (!m) return v;
  if (depth > 16 || !(m[1] in raw)) throw new Error(`Bad colour alias ${v}`);
  return resolve(raw[m[1]], depth + 1);
};
const camel = (s) => s.replace(/[-.](\w)/g, (_, c) => c.toUpperCase());
const px = (v) => (typeof v === 'number' ? v : parseFloat(v));

const colors = Object.fromEntries(Object.entries(raw).map(([k, v]) => [camel(k), resolve(v)]));
const spacing = Object.fromEntries(tokens.spacing.tokens.map((t) => [camel(t.name), px(t.value)]));
const radius = Object.fromEntries(tokens.radius.tokens.map((t) => [camel(t.name), px(t.value)]));

// React Native loads each weight as its own font family (via @expo-google-fonts).
const FONT_FILES = {
  display: { 700: 'BricolageGrotesque_700Bold', 800: 'BricolageGrotesque_800ExtraBold' },
  body: { 400: 'HankenGrotesk_400Regular', 600: 'HankenGrotesk_600SemiBold' },
  mono: { 400: 'DMMono_400Regular' },
};
const text = {};
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const fam = s.family ?? group.family;
    const size = px(s.fontSize);
    const family = FONT_FILES[fam]?.[s.fontWeight];
    if (!family) throw new Error(`No font file mapped for ${fam} ${s.fontWeight}`);
    const ls = s.letterSpacing ? parseFloat(s.letterSpacing) : 0;
    text[camel(s.name)] = {
      fontFamily: family,
      fontSize: size,
      lineHeight: Math.round(Number(s.lineHeight) * size),
      // RN letterSpacing is in points, so convert from em.
      letterSpacing: Math.round(ls * size * 100) / 100,
      ...(group.family === 'mono' ? { textTransform: 'uppercase' } : {}),
    };
  }
}

const out = `// GENERATED by scripts/generate.mjs from tokens.json — do not edit by hand.
// Source of truth: the Hadeda Design System (https://claude.ai/artifact/9CioMoPduhMGkT2doc7LL8).

export const colors = ${JSON.stringify(colors, null, 2)} as const;

export const spacing = ${JSON.stringify(spacing, null, 2)} as const;

export const radius = ${JSON.stringify(radius, null, 2)} as const;

export const text = ${JSON.stringify(text, null, 2)} as const;

/** Font files to load with expo-font / useFonts, keyed by the family names used in \`text\`. */
export const fontFamilies = ${JSON.stringify(FONT_FILES, null, 2)} as const;

/** Motion curves and durations. Interface glides; the game world steps like a sprite. */
export const motion = {
  outExpo: [0.16, 1, 0.3, 1],
  overshoot: [0.34, 1.56, 0.64, 1],
  inOut: [0.7, 0, 0.2, 1],
  sheetMs: 700,
  pressMs: 200,
  scorePopMs: 320,
  spriteFps: 8,
  parallax: { sky: 0.1, mountains: 0.3, houses: 0.6, obstacles: 1 },
} as const;

/** One art pixel on phones. Pixel assets render at whole-number multiples of this. */
export const ART_PIXEL = ${spacing.artPixel};

export type ColorName = keyof typeof colors;
export type TextStyleName = keyof typeof text;

export const theme = { colors, spacing, radius, text, motion } as const;
export default theme;
`;
writeFileSync(join(root, 'src/index.ts'), out);
console.log(`design-tokens: ${Object.keys(colors).length} colours, ${Object.keys(text).length} text styles`);
